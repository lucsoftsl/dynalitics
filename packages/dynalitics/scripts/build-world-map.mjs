// Builds src/read/geo/world-map.ts, the country shapes served by GET /api/world-map (docs/SPEC.md 21), from Natural Earth's 1:110m Admin 0 countries
// (public domain, https://www.naturalearthdata.com). No dependencies: the projection is equirectangular and the
// output is SVG path data with integer, relative coordinates (small and gzips well).
//
//   curl -sSfLo ne.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson
//   node packages/dynalitics/scripts/build-world-map.mjs ne.geojson
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/** 1920 units wide: integer coordinates still hold half a pixel of a 960 px map. */
export const WIDTH = 1920;
const SCALE = WIDTH / 360;
/** Antarctica is left out (no visitors, half the map); the map is cropped to the remaining land. */
const SKIP = new Set(['AQ']);
/** Natural Earth has no ISO code for these breakaway areas; their visitors are counted by the country they belong to. */
const BY_NAME = { Somaliland: 'SO', 'N. Cyprus': 'CY' };

export function isoCode(props) {
  const code = props.ISO_A2_EH !== '-99' ? props.ISO_A2_EH : BY_NAME[props.NAME];
  return typeof code === 'string' && /^[A-Z]{2}$/.test(code) ? code : null;
}

function polygonsOf(geometry) {
  if (geometry.type === 'Polygon') return [geometry.coordinates];
  if (geometry.type === 'MultiPolygon') return geometry.coordinates;
  return [];
}

/** One ring as `M x y l dx dy ... z`, integer pixels; repeated points after rounding are dropped. */
function ringPath(ring, top) {
  const pts = [];
  for (const [lon, lat] of ring) {
    const p = [Math.round((lon + 180) * SCALE), Math.round((top - lat) * SCALE)];
    const last = pts[pts.length - 1];
    if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
  }
  if (pts.length > 1) {
    const [a, b] = [pts[0], pts[pts.length - 1]];
    if (a[0] === b[0] && a[1] === b[1]) pts.pop();
  }
  if (pts.length < 3) return '';
  let d = `M${pts[0][0]} ${pts[0][1]}l`;
  for (let i = 1; i < pts.length; i++) {
    const dx = pts[i][0] - pts[i - 1][0];
    const dy = pts[i][1] - pts[i - 1][1];
    d += `${i > 1 && dx >= 0 ? ' ' : ''}${dx}${dy >= 0 ? ' ' : ''}${dy}`;
  }
  return `${d}z`;
}

export function buildWorldMap(geojson) {
  const features = geojson.features
    .map((f) => ({ code: isoCode(f.properties), polygons: polygonsOf(f.geometry) }))
    .filter((f) => f.code !== null && !SKIP.has(f.code));
  let top = -90;
  let bottom = 90;
  for (const f of features)
    for (const poly of f.polygons)
      for (const [, lat] of poly[0]) {
        top = Math.max(top, lat);
        bottom = Math.min(bottom, lat);
      }
  const byCode = new Map();
  for (const f of features) {
    const d = f.polygons.flatMap((poly) => poly.map((ring) => ringPath(ring, top))).join('');
    if (d) byCode.set(f.code, (byCode.get(f.code) ?? '') + d);
  }
  const countries = [...byCode.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([code, d]) => ({ code, d }));
  return { width: WIDTH, height: Math.ceil((top - bottom) * SCALE), countries };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const input = process.argv[2];
  if (!input)
    throw new Error('usage: node scripts/build-world-map.mjs <ne_110m_admin_0_countries.geojson>');
  const map = buildWorldMap(JSON.parse(await readFile(input, 'utf8')));
  const out = join(root, 'src/read/geo/world-map.ts');
  const source = [
    '// GENERATED by scripts/build-world-map.mjs from Natural Earth 1:110m Admin 0 countries v5.1.2 (public domain).',
    '// Do not edit by hand.',
    "import type { WorldMapData } from '../../protocol.js';",
    '',
    `export const WORLD_MAP: WorldMapData = JSON.parse(${JSON.stringify(JSON.stringify(map))}) as WorldMapData;`,
    '',
  ].join('\n');
  await writeFile(out, source);
  console.log(`${out}: ${map.countries.length} countries, ${map.width}x${map.height}`);
}
